import type { ParsedHar, ParsedHarRequest } from '../har/types.ts'
import { createTargetPolicy } from '../api/policy.ts'
import type { CorrelationConfig } from './k6.ts'

export interface JMeterOptions {
  baseUrl: string
  allowedOrigins?: string[]
  threads?: number
  rampUpSeconds?: number
  loops?: number
  durationSeconds?: number
  correlations?: CorrelationConfig[]
}

export function generateJmx(har: ParsedHar, options: JMeterOptions): string {
  createTargetPolicy(options.baseUrl, options.allowedOrigins)
  const threads = options.threads ?? 1
  const rampUp = options.rampUpSeconds ?? 1
  const loops = options.loops ?? 1
  const hasDuration = options.durationSeconds !== undefined
  return `<?xml version="1.0" encoding="UTF-8"?>
<jmeterTestPlan version="1.2" properties="5.0" jmeter="5.6.3">
  <hashTree>
    <TestPlan guiclass="TestPlanGui" testclass="TestPlan" testname="HAR Replay" enabled="true">
      <stringProp name="TestPlan.comments">Generated by test-agent</stringProp>
      <boolProp name="TestPlan.functional_mode">false</boolProp>
      <boolProp name="TestPlan.tearDown_on_shutdown">true</boolProp>
      <boolProp name="TestPlan.serialize_threadgroups">false</boolProp>
      <elementProp name="TestPlan.user_defined_variables" elementType="Arguments" guiclass="ArgumentsPanel" testclass="Arguments" testname="User Defined Variables" enabled="true">
        <collectionProp name="Arguments.arguments">
${(options.correlations ?? []).map(renderVariable).join('\n')}
        </collectionProp>
      </elementProp>
    </TestPlan>
    <hashTree>
      <ThreadGroup guiclass="ThreadGroupGui" testclass="ThreadGroup" testname="HAR Users" enabled="true">
        <stringProp name="ThreadGroup.num_threads">${threads}</stringProp>
        <stringProp name="ThreadGroup.ramp_time">${rampUp}</stringProp>
        <boolProp name="ThreadGroup.scheduler">${hasDuration}</boolProp>
        <stringProp name="ThreadGroup.duration">${hasDuration ? options.durationSeconds : ''}</stringProp>
        <stringProp name="ThreadGroup.delay"></stringProp>
        <elementProp name="ThreadGroup.main_controller" elementType="LoopController" guiclass="LoopControlPanel" testclass="LoopController" testname="Loop Controller" enabled="true">
          <boolProp name="LoopController.continue_forever">false</boolProp>
          <intProp name="LoopController.loops">${loops}</intProp>
        </elementProp>
      </ThreadGroup>
      <hashTree>
${har.entries.map((request, index) => renderSampler(request, options.baseUrl, index, options)).join('\n')}
      </hashTree>
    </hashTree>
  </hashTree>
</jmeterTestPlan>
`
}

function renderSampler(request: ParsedHarRequest, baseUrl: string, index: number, options: JMeterOptions): string {
  const base = new URL(baseUrl)
  const original = new URL(request.url)
  const target = new URL(base.toString())
  target.pathname = joinPath(base.pathname, original.pathname)
  target.search = original.search
  const headers = request.headers.filter(header => !header.sensitive)
  return `        <HTTPSamplerProxy guiclass="HttpTestSampleGui" testclass="HTTPSamplerProxy" testname="${xmlEscape(`${request.method} ${target.pathname}`)}" enabled="true">
          <elementProp name="HTTPsampler.Arguments" elementType="Arguments" guiclass="HTTPArgumentsPanel" testclass="Arguments" testname="User Defined Variables" enabled="true">
${request.body === undefined ? '' : renderRawBody(request.body)}
          </elementProp>
          <stringProp name="HTTPSampler.domain">${xmlEscape(target.hostname)}</stringProp>
          <stringProp name="HTTPSampler.port">${xmlEscape(target.port || (target.protocol === 'https:' ? '443' : '80'))}</stringProp>
          <stringProp name="HTTPSampler.protocol">${xmlEscape(target.protocol.replace(':', ''))}</stringProp>
          <stringProp name="HTTPSampler.path">${xmlEscape(target.pathname + target.search)}</stringProp>
          <stringProp name="HTTPSampler.method">${xmlEscape(request.method)}</stringProp>
          <boolProp name="HTTPSampler.follow_redirects">false</boolProp>
          <boolProp name="HTTPSampler.auto_redirects">false</boolProp>
          <boolProp name="HTTPSampler.use_keepalive">true</boolProp>
          ${request.body === undefined ? '' : '<boolProp name="HTTPSampler.postBodyRaw">true</boolProp>'}
        </HTTPSamplerProxy>
        <hashTree>
${headers.map(renderHeaderManager).join('\n')}
${(options.correlations ?? []).filter(item => item.sourceIndex === index).map(renderExtractor).join('\n')}
        </hashTree>`
}

function renderVariable(config: CorrelationConfig): string {
  return `          <elementProp name="${xmlEscape(config.variableName)}" elementType="Argument">
            <stringProp name="Argument.name">${xmlEscape(config.variableName)}</stringProp>
            <stringProp name="Argument.value">\${__V(${xmlEscape(config.variableName)})}</stringProp>
            <stringProp name="Argument.metadata">=</stringProp>
          </elementProp>`
}

function renderExtractor(config: CorrelationConfig): string {
  return `          <JSONPostProcessor guiclass="JSONPostProcessorGui" testclass="JSONPostProcessor" testname="Extract ${xmlEscape(config.variableName)}" enabled="true">
            <stringProp name="JSONPostProcessor.referenceName">${xmlEscape(config.variableName)}</stringProp>
            <stringProp name="JSONPostProcessor.jsonPathExprs">${xmlEscape(jsonPathToJMeter(config.jsonPath))}</stringProp>
            <stringProp name="JSONPostProcessor.match_numbers">1</stringProp>
            <stringProp name="JSONPostProcessor.defaultValues">NOT_FOUND</stringProp>
          </JSONPostProcessor>
          <hashTree/>`
}

function jsonPathToJMeter(path: string): string {
  return path.replace(/^\$/, '')
}

function renderHeaderManager(header: { name: string; value: string }): string {
  return `          <HeaderManager guiclass="HeaderPanel" testclass="HeaderManager" testname="${xmlEscape(header.name)}" enabled="true">
            <collectionProp name="HeaderManager.headers">
              <elementProp name="" elementType="Header">
                <stringProp name="Header.name">${xmlEscape(header.name)}</stringProp>
                <stringProp name="Header.value">${xmlEscape(header.value)}</stringProp>
              </elementProp>
            </collectionProp>
          </HeaderManager>
          <hashTree/>`
}

function renderRawBody(body: string): string {
  return `            <elementProp name="" elementType="HTTPArgument">
              <boolProp name="HTTPArgument.always_encode">false</boolProp>
              <stringProp name="Argument.value">${xmlEscape(body)}</stringProp>
              <stringProp name="Argument.metadata">=</stringProp>
            </elementProp>`
}

function joinPath(basePath: string, requestPath: string): string {
  const left = basePath.replace(/\/$/, '')
  const right = requestPath.startsWith('/') ? requestPath : `/${requestPath}`
  return `${left}${right}` || '/'
}

function xmlEscape(value: string): string {
  return value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&apos;')
}
